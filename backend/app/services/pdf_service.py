    @staticmethod
    def _safe_float(val: Any, default: float = 0.0) -> float:
        """Safely parse float value with fallback on None or invalid input."""
        if val is None:
            return default
        try:
            return float(val)
        except (ValueError, TypeError):
            return default

    @staticmethod
    def _safe_int(val: Any, default: int = 0) -> int:
        """Safely parse integer value with fallback on None or invalid input."""
        if val is None:
            return default
        try:
            return int(val)
        except (ValueError, TypeError):
            return default

    @staticmethod
    def _safe_text(val: Any) -> str:
        """Escape XML entities and remove non-printable/corrupt characters for ReportLab."""
        if val is None:
            return "N/A"
        s = str(val)
        # Strip potential surrogate characters or emojis that crash standard PDF Type 1 fonts
        s = re.sub(r"[^\x00-\x7F]+", " ", s)
        # XML entity escaping
        return html.escape(s.strip(), quote=False)

    @staticmethod
    def _extract_dict(obj: Any) -> Dict[str, Any]:
        """Convert input data to clean Python dict."""
        if hasattr(obj, "model_dump"):
            return obj.model_dump()
        elif hasattr(obj, "dict"):
            return obj.dict()
        elif isinstance(obj, dict):
            return obj
        return {}

