class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and stamp total page numbers and running headers/footers."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int) -> None:
        """Draw professional header and footer rules on all pages."""
        self.saveState()

        # Running Header
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#1E3A8A"))
        self.drawString(36, 11 * inch - 28, "TravelSenseAI™  |  Executive Travel Dossier & Planning Report")

        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        self.drawRightString(8.5 * inch - 36, 11 * inch - 28, "Strict Facts & Provenance Verified")

        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(36, 11 * inch - 32, 8.5 * inch - 36, 11 * inch - 32)

        # Running Footer
        self.line(36, 34, 8.5 * inch - 36, 34)

        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        timestamp_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
        self.drawString(36, 22, f"Generated by TravelSenseAI Intelligence Engine  •  {timestamp_str}")

        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(8.5 * inch - 36, 22, page_str)

        self.restoreState()


